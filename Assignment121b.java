//121.WAP on using Access Specifiers  outside the package  
//by becoming subclass.(using inheritance) for non static methods.
package accessspecifier;

public class Assignment121b 
{
	public void Enrollnment1()
	{
		System.out.println("Enrollment1 for public details");
	}
	protected void Enrollnment2()
	{
		System.out.println("Enrollment2 for protected details");
	}
	 void Enrollnment3()
	{
		System.out.println("Enrollment3  for default details");
	}
	private void Enrollnment4()
	{
		System.out.println("Enrollment4 for private details");
	}
	

}
